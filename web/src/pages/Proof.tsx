import { useEffect, useState } from 'react'
import { Card, Empty, ErrorBox, Spinner } from '../components/ui'
import { useAuth } from '../lib/auth'
import { useGoalData } from '../lib/goalData'
import { supabase } from '../lib/supabase'

interface Entry { id: string; skill_id: string | null; proof_type: string; evidence_summary: string; verified_at: string }
const TYPE: Record<string, { label: string; tone: string }> = {
  practice: { label: 'Practice', tone: 'bg-slate-700' },
  peer_taught: { label: 'Peer taught', tone: 'bg-sky-500/20 text-sky-300' },
  simulation_passed: { label: 'Simulation passed', tone: 'bg-emerald-500/20 text-emerald-300' },
  explain_back_passed: { label: 'Explain-back passed', tone: 'bg-indigo-500/20 text-indigo-300' },
}

export default function Proof() {
  const { goal, skills } = useGoalData()
  const { session } = useAuth()
  const [entries, setEntries] = useState<Entry[] | null>(null)
  const [error, setError] = useState('')
  const [copied, setCopied] = useState(false)
  const [shares, setShares] = useState<{ slug: string; goal_title: string | null; created_at: string }[]>([])
  const [pubName, setPubName] = useState(session!.user.email?.split('@')[0] ?? '')
  const [sharing, setSharing] = useState(false)
  const [linkCopied, setLinkCopied] = useState('')
  const name = new Map(skills.map((s) => [s.id, s.skill_name]))
  useEffect(() => {
    supabase.from('shared_proofs').select('slug, goal_title, created_at').eq('user_id', session!.user.id).eq('goal_title', goal.goal_title).order('created_at', { ascending: false })
      .then(({ data }) => setShares(data ?? []))
  }, [session, goal.goal_title])

  async function publish() {
    setSharing(true); setError('')
    const slug = Array.from(crypto.getRandomValues(new Uint8Array(10)), (b) => 'abcdefghijklmnopqrstuvwxyz0123456789'[b % 36]).join('')
    const snapshot = entries!.map((e) => ({ date: new Date(e.verified_at).toLocaleDateString(), type: TYPE[e.proof_type]?.label ?? e.proof_type, skill: e.skill_id ? name.get(e.skill_id) ?? null : null, evidence: e.evidence_summary }))
    const { error } = await supabase.from('shared_proofs').insert({ slug, user_id: session!.user.id, display_name: pubName.trim() || null, goal_title: goal.goal_title, entries: snapshot })
    if (error) setError(error.message); else setShares((s) => [{ slug, goal_title: goal.goal_title, created_at: new Date().toISOString() }, ...s])
    setSharing(false)
  }
  async function revoke(slug: string) { await supabase.from('shared_proofs').delete().eq('slug', slug); setShares((s) => s.filter((x) => x.slug !== slug)) }
  const linkFor = (slug: string) => `${location.origin}/p/${slug}`
  async function copyLink(slug: string) { await navigator.clipboard.writeText(linkFor(slug)); setLinkCopied(slug); setTimeout(() => setLinkCopied(''), 1500) }

  useEffect(() => {
    // Skill-linked entries for this goal + unlinked ones (simulations) for this user.
    supabase.from('proof_ledger').select('*').eq('user_id', session!.user.id).order('verified_at', { ascending: false })
      .then(({ data, error }) => {
        if (error) return setError(error.message)
        const ids = new Set(skills.map((s) => s.id))
        setEntries((data as Entry[]).filter((e) => !e.skill_id || ids.has(e.skill_id)))
      })
  }, [session, skills])

  const markdown = () => [
    `# Skill Provenance: ${goal.goal_title}`, '',
    `_Generated by LearnLoop on ${new Date().toLocaleDateString()} — ${entries!.length} verified entries_`, '',
    ...entries!.map((e) => `- **${new Date(e.verified_at).toLocaleDateString()}** · ${TYPE[e.proof_type]?.label ?? e.proof_type}${e.skill_id ? ` · ${name.get(e.skill_id)}` : ''}\n  ${e.evidence_summary}`),
  ].join('\n')

  function download() {
    const a = document.createElement('a')
    a.href = URL.createObjectURL(new Blob([markdown()], { type: 'text/markdown' }))
    a.download = `learnloop-proof-${goal.goal_title.toLowerCase().replace(/\W+/g, '-')}.md`
    a.click(); URL.revokeObjectURL(a.href)
  }
  async function copy() { await navigator.clipboard.writeText(markdown()); setCopied(true); setTimeout(() => setCopied(false), 1500) }

  if (error) return <ErrorBox message={error} />
  if (!entries) return <Spinner />
  return (
    <div className="stagger space-y-4">
      <div className="flex flex-wrap items-center justify-between gap-2"><h1 className="font-display text-3xl font-bold">Proof of work</h1>
        {entries.length > 0 && <div className="flex gap-2"><button className="rounded-lg border border-slate-600 px-3 py-1.5 text-sm" onClick={copy}>{copied ? 'Copied ✓' : 'Copy markdown'}</button>
          <button className="btn text-sm" onClick={download}>Export .md</button></div>}</div>
      <p className="text-sm text-slate-400">A timestamped, evidence-backed ledger of what you've verifiably learned — not a badge wall.</p>
      {entries.length === 0 ? <Empty title="Nothing verified yet" hint="Pass an explain-back, finish a practice session, or pass a simulation to add entries." /> : (
        <ol className="space-y-2">{entries.map((e) => (
          <li key={e.id}><Card className="!p-3"><div className="flex flex-wrap items-center gap-2 text-sm">
            <span className={`rounded px-1.5 py-0.5 text-xs ${TYPE[e.proof_type]?.tone}`}>{TYPE[e.proof_type]?.label ?? e.proof_type}</span>
            {e.skill_id && <b>{name.get(e.skill_id)}</b>}<span className="ml-auto text-slate-500">{new Date(e.verified_at).toLocaleString()}</span></div>
            <p className="mt-1 text-sm text-slate-300">{e.evidence_summary}</p></Card></li>
        ))}</ol>
      )}
      {entries.length > 0 && (
        <Card title="🔗 Public proof page">
          <p className="mb-3 text-sm text-slate-400">Publish a read-only snapshot anyone can open, with no sign-in. It shows only the entries above and the name you choose, and you can remove it any time.</p>
          <div className="flex flex-wrap gap-2"><input className="input min-w-0 flex-1" placeholder="Name to display" value={pubName} maxLength={60} onChange={(e) => setPubName(e.target.value)} />
            <button className="btn" disabled={sharing} onClick={publish}>{sharing ? 'Publishing…' : 'Create public link'}</button></div>
          {shares.length > 0 && <ul className="mt-3 space-y-2">{shares.map((sh) => (
            <li key={sh.slug} className="flex flex-wrap items-center gap-2 rounded-xl bg-white/[.05] px-3 py-2 text-sm">
              <a className="min-w-0 flex-1 truncate text-indigo-300 hover:underline" href={linkFor(sh.slug)} target="_blank" rel="noopener noreferrer">{linkFor(sh.slug)}</a>
              <button className="rounded-lg border border-white/15 px-2 py-1 text-xs hover:bg-white/10" onClick={() => copyLink(sh.slug)}>{linkCopied === sh.slug ? 'Copied ✓' : 'Copy'}</button>
              <button className="rounded-lg border border-red-400/30 px-2 py-1 text-xs text-red-300 hover:bg-red-500/10" onClick={() => revoke(sh.slug)}>Remove</button></li>))}</ul>}
        </Card>)}

      <Card title="Roadmap (vision)"><p className="text-sm text-slate-400">Pod-to-Opportunity Pipeline: once a pod's collective ledger crosses a threshold, surface a matched real-world opportunity — an open-source issue for dev pods, a language-exchange group, a pro-bono campaign brief.</p></Card>
    </div>
  )
}
